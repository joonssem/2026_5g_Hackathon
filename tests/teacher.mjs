import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import vm from 'node:vm';
const html=readFileSync(new URL('../teacher.html',import.meta.url),'utf8');
const count=(html.match(/class="slide"/g)||[]).length;
assert.equal(count,6);
const slides=Array.from({length:count},()=>({hidden:false}));
const elements=new Map(),events={};
const el=id=>{if(!elements.has(id))elements.set(id,{textContent:'',disabled:false});return elements.get(id);};
const document={querySelectorAll:()=>slides,getElementById:el,addEventListener:(key,fn)=>events[key]=fn,documentElement:{}};
vm.runInNewContext(readFileSync(new URL('../teacher.js',import.meta.url),'utf8'),{document});
assert.deepEqual(slides.map(s=>s.hidden),[false,true,true,true,true,true]);
assert.equal(el('board-previous').disabled,true);
for(let i=0;i<10;i++)el('board-next').onclick();
assert.equal(el('board-count').textContent,'6 / 6');
assert.equal(el('board-next').disabled,true);
events.keydown({key:'PageUp',preventDefault(){}});
assert.equal(el('board-count').textContent,'5 / 6');
events.keydown({key:'ArrowLeft',ctrlKey:true,preventDefault(){}});
assert.equal(el('board-count').textContent,'5 / 6');
for(let i=0;i<10;i++)el('board-previous').onclick();
assert.equal(el('board-count').textContent,'1 / 6');
await el('fullscreen').onclick();
assert.match(el('board-status').textContent,/지원하지/);
for(const match of html.matchAll(/(?:src|href)="([^"#]+\.(?:css|js))"/g))assert.ok(existsSync(new URL('../'+match[1],import.meta.url)));
const last=html.slice(html.indexOf('aria-labelledby="title-6"'));
assert.match(last,/assets\/student-page-qr.svg/);
assert.match(last,/https:\/\/joonssem.github.io\/2026_5g_Hackathon\//);
assert.doesNotMatch(html,/Teams/);
assert.ok(existsSync(new URL('../assets/student-page-qr.svg',import.meta.url)));
console.log('PASS: 전자칠판 6장, 단일 화면 표시, 처음·끝 이동 제한, 키보드 이동, 전체 화면 미지원 안내, 참조 파일');
